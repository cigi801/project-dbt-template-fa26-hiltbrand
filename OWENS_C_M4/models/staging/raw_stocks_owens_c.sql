
WITH cleaned AS (
    SELECT
        UPPER(TRIM(SYMBOL)) AS SYMBOL,
        DATETIME::TIMESTAMP_NTZ AS DATETIME,
        TRY_TO_DOUBLE(OPEN) AS OPEN,
        TRY_TO_DOUBLE(HIGH) AS HIGH,
        TRY_TO_DOUBLE(LOW) AS LOW,
        TRY_TO_DOUBLE(CLOSE) AS CLOSE,
        TRY_TO_NUMBER(VOLUME) AS VOLUME
    FROM {{ source('raw', 'STOCKS_OWENS_C') }}
)

SELECT *
FROM cleaned
WHERE SYMBOL IS NOT NULL
  AND SYMBOL <> ''
  AND DATETIME IS NOT NULL

QUALIFY ROW_NUMBER() OVER (
    PARTITION BY SYMBOL, DATETIME
    ORDER BY DATETIME DESC
) = 1
