
WITH cleaned AS (
    SELECT
        UPPER(TRIM(CITY)) AS CITY,
        DATE::DATE AS DATE,
        TRY_TO_DOUBLE(MAX_TEMP) AS MAX_TEMP,
        TRY_TO_DOUBLE(MIN_TEMP) AS MIN_TEMP,
        TRY_TO_DOUBLE(PRECIP) AS PRECIP,
        TRY_TO_DOUBLE(MAX_WIND) AS MAX_WIND,
        TRY_TO_NUMBER(WEATHER_CODE) AS WEATHER_CODE,
        TRY_TO_DOUBLE(MAX_TEMP_F) AS MAX_TEMP_F,
        TRY_TO_DOUBLE(MIN_TEMP_F) AS MIN_TEMP_F
    FROM {{ source('raw', 'WEATHER_OWENS_C') }}
)

SELECT *
FROM cleaned
WHERE CITY IS NOT NULL
  AND CITY <> ''
  AND DATE IS NOT NULL

QUALIFY ROW_NUMBER() OVER (
    PARTITION BY CITY, DATE
    ORDER BY DATE DESC
) = 1
