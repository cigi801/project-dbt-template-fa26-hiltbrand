
WITH cleaned AS (
    SELECT
        TRY_TO_NUMBER(ID)::NUMBER(38,0) AS ID,
        TO_TIMESTAMP_NTZ(DATETIME, 0) AS DATETIME,
        NULLIF(TRIM(CATEGORY), '') AS CATEGORY,
        NULLIF(TRIM(HEADLINE), '') AS HEADLINE,
        NULLIF(TRIM(IMAGE), '') AS IMAGE,
        NULLIF(TRIM(RELATED), '') AS RELATED,
        NULLIF(TRIM(SOURCE), '') AS SOURCE,
        NULLIF(TRIM(SUMMARY), '') AS SUMMARY,
        NULLIF(TRIM(URL), '') AS URL,
        PUBLISHED_DATE::TIMESTAMP_TZ AS PUBLISHED_DATE
    FROM {{ source('raw', 'NEWS_OWENS_C') }}
)

SELECT *
FROM cleaned
WHERE ID IS NOT NULL

QUALIFY ROW_NUMBER() OVER (
    PARTITION BY ID
    ORDER BY PUBLISHED_DATE DESC NULLS LAST
) = 1
